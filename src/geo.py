def hub_accepts(mode: str, hub: str) -> bool:
    """Whether a hub can physically handle freight of this transport mode."""
    if mode == "sea":
        return hub in PORT_HUBS
    if mode == "air":
        return hub in AIR_HUBS
    return hub not in SEA_ONLY


